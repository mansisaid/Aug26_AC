//Write a Java program that checks if a predefined number is negative using an if-else statement and displays the result. 
class CheckNegativeNum{

	public static void main(String args[]){

		int num1 = -10;

		if(num1 < 0){
				System.out.println("Number " + num1 + " is Negative");
		}
		else{
			System.out.println("Number " + num1 + " is not negative");
		}
	}

}
