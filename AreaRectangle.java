//Write a Java program that calculates the area of a rectangle using the formula area = length * width. Use predefined values for length and width. 
class AreaRectangle{

	public static void main(String args[]){

		int length = 9;
		int width = 5;

		int area = length * width;

		System.out.println("Length of rectangle is:" + length);
		System.out.println("Width of rectangle is:" + width);
		System.out.println("Calculated Area is:" + area);

	
	}

}