 //Write a Java program that checks if a predefined number is positive using an if-else statement and prints the appropriate message. 
class CheckPositiveNum{

	public static void main(String args[]){

		int num = 5;

		if(num > 0){
				System.out.println("Number " + num + " is Positive");
		}
		else{
			System.out.println("Number " + num + " is not positive");
		}
	}

}
